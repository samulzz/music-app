const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('nation', {
  getSession: () => ipcRenderer.invoke('session:get'),
  login: (credentials) => ipcRenderer.invoke('auth:login', credentials),
  register: (credentials) => ipcRenderer.invoke('auth:register', credentials),
  logout: () => ipcRenderer.invoke('auth:logout'),
  checkForUpdate: () => ipcRenderer.invoke('updates:check'),
  openUpdateDownload: (url) => ipcRenderer.invoke('updates:open-download', url),
  search: (query) => ipcRenderer.invoke('music:search', query),
  prepareStream: (song) => ipcRenderer.invoke('music:prepare-stream', song),
  downloadSong: (song) => ipcRenderer.invoke('music:download', song),
  isSongDownloaded: (song) => ipcRenderer.invoke('music:is-downloaded', song),
  previewSpotify: (url) => ipcRenderer.invoke('spotify:preview', url),
  getLibrary: () => ipcRenderer.invoke('library:list'),
  saveToLibrary: (song) => ipcRenderer.invoke('library:save', song),
  removeFromLibrary: (serverId) => ipcRenderer.invoke('library:remove', serverId),
  getPlaylists: () => ipcRenderer.invoke('playlists:list'),
  getPlaylistSongs: (id) => ipcRenderer.invoke('playlists:songs', id),
  getDailyMix: () => ipcRenderer.invoke('recommendations:daily'),
  reportPlayback: (payload) => ipcRenderer.invoke('recommendations:listen', payload),
  getPersonalPlaylists: () => ipcRenderer.invoke('personal-playlists:list'),
  getPersonalPlaylistSongs: (id) => ipcRenderer.invoke('personal-playlists:songs', id),
  createPersonalPlaylist: (playlist) => ipcRenderer.invoke('personal-playlists:create', playlist),
  updatePersonalPlaylist: (playlistId, playlist) => ipcRenderer.invoke('personal-playlists:update', playlistId, playlist),
  deletePersonalPlaylist: (playlistId) => ipcRenderer.invoke('personal-playlists:delete', playlistId),
  addSongToPersonalPlaylist: (playlistId, songId) => ipcRenderer.invoke('personal-playlists:add-song', playlistId, songId),
  removeSongFromPersonalPlaylist: (playlistId, songId) => ipcRenderer.invoke('personal-playlists:remove-song', playlistId, songId),
  getFriends: () => ipcRenderer.invoke('friends:list'),
  searchFriends: (query) => ipcRenderer.invoke('friends:search', query),
  getFriendRequests: () => ipcRenderer.invoke('friends:requests'),
  sendFriendRequest: (username) => ipcRenderer.invoke('friends:send-request', username),
  acceptFriendRequest: (requestId) => ipcRenderer.invoke('friends:accept-request', requestId),
  declineFriendRequest: (requestId) => ipcRenderer.invoke('friends:decline-request', requestId),
  removeFriend: (username) => ipcRenderer.invoke('friends:remove', username),
  updateFriendPresence: (payload) => ipcRenderer.invoke('friends:update-presence', payload),
  clearFriendPresence: () => ipcRenderer.invoke('friends:clear-presence'),
  updateConnectPlayback: (payload) => ipcRenderer.invoke('connect:heartbeat', payload),
  controlConnectPlayback: (payload) => ipcRenderer.invoke('connect:control', payload),
  createJam: (payload) => ipcRenderer.invoke('jam:create', payload),
  joinJam: (code) => ipcRenderer.invoke('jam:join', code),
  getJam: (code) => ipcRenderer.invoke('jam:get', code),
  updateJamState: (code, payload) => ipcRenderer.invoke('jam:update-state', code, payload),
  leaveJam: (code) => ipcRenderer.invoke('jam:leave', code),
  copyText: (text) => ipcRenderer.invoke('clipboard:write-text', text),
  getDiscordStatus: () => ipcRenderer.invoke('discord:get-status'),
  configureDiscord: (settings) => ipcRenderer.invoke('discord:configure', settings),
  updateDiscordActivity: (payload) => ipcRenderer.invoke('discord:update-activity', payload),
  clearDiscordActivity: () => ipcRenderer.invoke('discord:clear-activity'),
});
